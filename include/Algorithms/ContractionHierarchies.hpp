// ---------------------------------------------------------------------------
// ContractionHierarchiesRouter: State-of-the-Art Contraction Hierarchies (CH)
//
// 1. Offline Preprocessing (Node Contraction & Shortcut Generation):
//    - Assigns an importance rank to each airport based on connectivity degree.
//    - Peripheral regional spokes (e.g. domestic airstrips) receive low ranks
//      and are contracted first.
//    - International mega-hubs (e.g. DXB, LHR, FRA, JFK) receive the highest
//      ranks and are contracted last.
//    - When a node v is contracted, necessary shortcuts (u -> w) with
//      weight = cost(u->v) + cost(v->w) are added between its neighbors,
//      recording v as the shortcut's unpacked middle node.
//
// 2. Online Hierarchical Query (Bidirectional Upward Search):
//    - Forward Search from Source: Explores strictly UPWARD edges
//      where rank(target) > rank(source).
//    - Backward Search from Destination: Explores strictly UPWARD edges in reverse
//      where rank(source) > rank(target).
//    - Both searches meet at high-ranking continental and global hubs.
//    - Meeting corridors are unpacked recursively via recorded shortcut middle nodes.
//
// 3. Timetable Evaluation:
//    - Candidate corridors generated by the CH query are forwarded to localized
//      timetable forward sweep to determine the exact flight schedule.
// ---------------------------------------------------------------------------
class ContractionHierarchiesRouter {
public:
  const uint32_t INF = std::numeric_limits<uint32_t>::max();

  struct CHEdge {
    uint32_t target;
    uint32_t cost;
    uint32_t duration;
    int32_t middle_node; // -1 if original flight edge, >= 0 if shortcut
  };

  struct CHGraph {
    std::vector<std::vector<CHEdge>> forward_up;
    std::vector<std::vector<CHEdge>> backward_up;
    std::vector<uint32_t> node_rank;
    bool is_preprocessed = false;
  };

  // Min-heap entry for Bidirectional CH
  struct CHPQItem {
    uint32_t cost;
    uint32_t node;

    bool operator>(const CHPQItem &other) const {
      return cost > other.cost;
    }
  };

  // Preprocess the graph: node ordering + shortcut contraction
  static void preprocess(const std::vector<std::vector<uint32_t>> &static_graph,
                         const std::vector<std::vector<uint16_t>> &static_min_price,
                         const std::vector<std::vector<uint16_t>> &static_min_duration,
                         CHGraph &ch, OptimizeFor mode) {

    size_t n = static_graph.size();
    ch.node_rank.assign(n, 0);
    ch.forward_up.assign(n, {});
    ch.backward_up.assign(n, {});

    // Compute node degrees for contraction ordering
    std::vector<std::pair<size_t, uint32_t>> deg_order;
    deg_order.reserve(n);
    for (size_t i = 0; i < n; ++i) {
      deg_order.push_back({static_graph[i].size(), static_cast<uint32_t>(i)});
    }
    std::sort(deg_order.begin(), deg_order.end());

    for (size_t r = 0; r < n; ++r) {
      ch.node_rank[deg_order[r].second] = static_cast<uint32_t>(r);
    }

    // Temporary full adjacency with edge weights
    std::vector<std::unordered_map<uint32_t, std::pair<uint32_t, uint32_t>>> adj(n);
    std::vector<std::unordered_map<uint32_t, std::pair<uint32_t, uint32_t>>> radj(n);
    std::unordered_map<uint64_t, int32_t> shortcut_middle;

    auto make_key = [](uint32_t u, uint32_t v) -> uint64_t {
      return (static_cast<uint64_t>(u) << 32) | v;
    };

    for (size_t u = 0; u < n; ++u) {
      for (size_t i = 0; i < static_graph[u].size(); ++i) {
        uint32_t v = static_graph[u][i];
        uint32_t p = static_min_price[u][i];
        uint32_t d = static_min_duration[u][i];
        adj[u][v] = {p, d};
        radj[v][u] = {p, d};
        shortcut_middle[make_key(static_cast<uint32_t>(u), v)] = -1;
      }
    }

    // Node contraction for spokes (degree <= 25) to avoid shortcut explosion
    for (const auto &item : deg_order) {
      uint32_t v = item.second;
      if (item.first > 25) {
        continue; // Keep dense hubs uncontracted as core overlay
      }

      std::vector<std::pair<uint32_t, std::pair<uint32_t, uint32_t>>> in_edges(radj[v].begin(), radj[v].end());
      std::vector<std::pair<uint32_t, std::pair<uint32_t, uint32_t>>> out_edges(adj[v].begin(), adj[v].end());

      for (const auto &in_e : in_edges) {
        uint32_t u = in_e.first;
        if (ch.node_rank[u] <= ch.node_rank[v]) continue; // Only contract through higher or uncontracted

        for (const auto &out_e : out_edges) {
          uint32_t w = out_e.first;
          if (u == w || ch.node_rank[w] <= ch.node_rank[v]) continue;

          uint32_t new_price = in_e.second.first + out_e.second.first;
          uint32_t new_dur = in_e.second.second + out_e.second.second;
          uint32_t metric = (mode == OptimizeFor::PRICE) ? new_price : new_dur;

          bool need_shortcut = true;
          auto it = adj[u].find(w);
          if (it != adj[u].end()) {
            uint32_t existing = (mode == OptimizeFor::PRICE) ? it->second.first : it->second.second;
            if (existing <= metric) {
              need_shortcut = false;
            }
          }

          if (need_shortcut) {
            adj[u][w] = {new_price, new_dur};
            radj[w][u] = {new_price, new_dur};
            shortcut_middle[make_key(u, w)] = static_cast<int32_t>(v);
          }
        }
      }
    }

    // Build final Upward CH Graphs
    for (size_t u = 0; u < n; ++u) {
      for (const auto &pair : adj[u]) {
        uint32_t v = pair.first;
        if (ch.node_rank[v] > ch.node_rank[u]) {
          int32_t mid = shortcut_middle[make_key(static_cast<uint32_t>(u), v)];
          ch.forward_up[u].push_back(CHEdge{v, pair.second.first, pair.second.second, mid});
        }
      }
      for (const auto &pair : radj[u]) {
        uint32_t v = pair.first; // v -> u
        if (ch.node_rank[v] > ch.node_rank[u]) {
          int32_t mid = shortcut_middle[make_key(v, static_cast<uint32_t>(u))];
          ch.backward_up[u].push_back(CHEdge{v, pair.second.first, pair.second.second, mid});
        }
      }
    }

    ch.is_preprocessed = true;
  }

  // Recursive shortcut unpacker
  static void unpack_shortcut(uint32_t u, uint32_t v, int32_t mid,
                              const CHGraph &ch, std::vector<uint32_t> &path) {
    if (mid == -1) {
      path.push_back(v);
      return;
    }
    // Find shortcut (u -> mid)
    int32_t mid1 = -1;
    for (const auto &e : ch.forward_up[u]) {
      if (e.target == static_cast<uint32_t>(mid)) {
        mid1 = e.middle_node;
        break;
      }
    }
    unpack_shortcut(u, static_cast<uint32_t>(mid), mid1, ch, path);

    // Find shortcut (mid -> v)
    int32_t mid2 = -1;
    for (const auto &e : ch.forward_up[static_cast<uint32_t>(mid)]) {
      if (e.target == v) {
        mid2 = e.middle_node;
        break;
      }
    }
    unpack_shortcut(static_cast<uint32_t>(mid), v, mid2, ch, path);
  }

  RoutingResult run(uint32_t source_id, uint32_t dest_id,
                    const std::vector<std::vector<flight>> &adjacency_list,
                    const std::vector<std::vector<uint32_t>> &static_graph,
                    const std::vector<std::vector<uint16_t>> &static_min_price,
                    const std::vector<std::vector<uint16_t>> &static_min_duration,
                    const std::vector<airport> &nodes, OptimizeFor mode,
                    uint32_t start_time, CHGraph &ch) {

    RoutingMetrics metrics = {0, 0};

    if (source_id == dest_id) {
      return {true, 0, 0, {}, metrics};
    }

    if (!ch.is_preprocessed) {
      preprocess(static_graph, static_min_price, static_min_duration, ch, mode);
    }

    // =========================================================================
    // HIGH-PERFORMANCE MULTI-CORRIDOR BIDIRECTIONAL UPWARD CH QUERY
    // =========================================================================
    uint32_t n = static_cast<uint32_t>(nodes.size());

    struct UpEdge {
      uint32_t parent;
      int32_t mid;
      uint32_t cost;
    };

    std::vector<uint32_t> f_best(n, INF);
    std::vector<uint32_t> b_best(n, INF);
    std::vector<std::vector<UpEdge>> f_edges(n);
    std::vector<std::vector<UpEdge>> b_edges(n);

    std::priority_queue<CHPQItem, std::vector<CHPQItem>, std::greater<CHPQItem>> f_pq;
    std::priority_queue<CHPQItem, std::vector<CHPQItem>, std::greater<CHPQItem>> b_pq;

    const uint32_t SLACK = (mode == OptimizeFor::PRICE) ? 120 : 240;

    f_best[source_id] = 0;
    f_pq.push({0, source_id});

    b_best[dest_id] = 0;
    b_pq.push({0, dest_id});

    std::vector<uint32_t> f_visited;
    std::vector<uint32_t> b_visited;

    while (!f_pq.empty()) {
      auto top = f_pq.top();
      f_pq.pop();
      uint32_t u = top.node;
      metrics.nodes_explored++;

      if (top.cost > f_best[u] + SLACK)
        continue;

      for (const auto &e : ch.forward_up[u]) {
        metrics.edges_relaxed++;
        uint32_t weight = (mode == OptimizeFor::PRICE) ? e.cost : e.duration;
        uint32_t new_c = top.cost + weight;

        if (new_c < f_best[e.target]) {
          if (f_best[e.target] == INF) {
            f_visited.push_back(e.target);
          }
          f_best[e.target] = new_c;
          f_pq.push({new_c, e.target});
          f_edges[e.target].push_back({u, e.middle_node, new_c});
        } else if (new_c <= f_best[e.target] + SLACK && f_edges[e.target].size() < 3) {
          f_pq.push({new_c, e.target});
          f_edges[e.target].push_back({u, e.middle_node, new_c});
        }
      }
    }

    while (!b_pq.empty()) {
      auto top = b_pq.top();
      b_pq.pop();
      uint32_t v = top.node;
      metrics.nodes_explored++;

      if (top.cost > b_best[v] + SLACK)
        continue;

      for (const auto &e : ch.backward_up[v]) {
        metrics.edges_relaxed++;
        uint32_t weight = (mode == OptimizeFor::PRICE) ? e.cost : e.duration;
        uint32_t new_c = top.cost + weight;

        if (new_c < b_best[e.target]) {
          if (b_best[e.target] == INF) {
            b_visited.push_back(e.target);
          }
          b_best[e.target] = new_c;
          b_pq.push({new_c, e.target});
          b_edges[e.target].push_back({v, e.middle_node, new_c});
        } else if (new_c <= b_best[e.target] + SLACK && b_edges[e.target].size() < 3) {
          b_pq.push({new_c, e.target});
          b_edges[e.target].push_back({v, e.middle_node, new_c});
        }
      }
    }

    // Meeting nodes with combined static cost
    std::vector<uint32_t> meeting_nodes;
    for (uint32_t u : f_visited) {
      if (b_best[u] != INF) {
        meeting_nodes.push_back(u);
      }
    }
    if (b_best[source_id] != INF) {
      meeting_nodes.push_back(source_id);
    }

    if (meeting_nodes.empty()) {
      return {false, 0, 0, {}, metrics};
    }

    std::sort(meeting_nodes.begin(), meeting_nodes.end(),
              [&](uint32_t a, uint32_t b) {
                return (f_best[a] + b_best[a]) < (f_best[b] + b_best[b]);
              });

    // Unpack multi-path corridors
    auto expand_forward = [&](auto &self, uint32_t curr,
                              std::vector<std::pair<uint32_t, int32_t>> &cur_legs,
                              std::vector<std::vector<std::pair<uint32_t, int32_t>>> &res) -> void {
      if (curr == source_id) {
        auto r = cur_legs;
        std::reverse(r.begin(), r.end());
        res.push_back(r);
        return;
      }
      for (const auto &ed : f_edges[curr]) {
        cur_legs.push_back({curr, ed.mid});
        self(self, ed.parent, cur_legs, res);
        cur_legs.pop_back();
        if (res.size() >= 3)
          break;
      }
    };

    auto expand_backward = [&](auto &self, uint32_t curr,
                               std::vector<std::pair<uint32_t, int32_t>> &cur_legs,
                               std::vector<std::vector<std::pair<uint32_t, int32_t>>> &res) -> void {
      if (curr == dest_id) {
        res.push_back(cur_legs);
        return;
      }
      for (const auto &ed : b_edges[curr]) {
        cur_legs.push_back({ed.parent, ed.mid});
        self(self, ed.parent, cur_legs, res);
        cur_legs.pop_back();
        if (res.size() >= 3)
          break;
      }
    };

    std::vector<std::vector<uint32_t>> corridors;
    for (size_t i = 0; i < std::min<size_t>(meeting_nodes.size(), 15); ++i) {
      uint32_t m = meeting_nodes[i];

      std::vector<std::pair<uint32_t, int32_t>> tmp_f;
      std::vector<std::vector<std::pair<uint32_t, int32_t>>> f_leg_paths;
      expand_forward(expand_forward, m, tmp_f, f_leg_paths);

      std::vector<std::pair<uint32_t, int32_t>> tmp_b;
      std::vector<std::vector<std::pair<uint32_t, int32_t>>> b_leg_paths;
      expand_backward(expand_backward, m, tmp_b, b_leg_paths);

      size_t added = 0;
      for (const auto &f_legs : f_leg_paths) {
        for (const auto &b_legs : b_leg_paths) {
          std::vector<uint32_t> corridor;
          corridor.push_back(source_id);
          uint32_t prev = source_id;

          for (const auto &leg : f_legs) {
            unpack_shortcut(prev, leg.first, leg.second, ch, corridor);
            prev = leg.first;
          }

          for (const auto &leg : b_legs) {
            unpack_shortcut(prev, leg.first, leg.second, ch, corridor);
            prev = leg.first;
          }

          corridor.erase(std::unique(corridor.begin(), corridor.end()),
                         corridor.end());
          if (!corridor.empty() && corridor.back() == dest_id) {
            corridors.push_back(std::move(corridor));
            added++;
          }
          if (added >= 3 || corridors.size() >= 35)
            break;
        }
        if (added >= 3 || corridors.size() >= 35)
          break;
      }
      if (corridors.size() >= 35)
        break;
    }

    // Evaluate corridors along actual timetable
    RoutingResult best_result;
    best_result.success = false;
    best_result.total_price = INF;
    best_result.total_time_mins = INF;

    for (const auto &corridor : corridors) {
      evaluate_corridor(corridor, adjacency_list, nodes, mode, start_time,
                        best_result, metrics);
    }

    best_result.metrics = metrics;
    return best_result;
  }

public:
  struct TimetableState {
    uint32_t current_time;
    uint32_t total_price;
    std::vector<flight> flights_taken;
  };

  void evaluate_corridor(const std::vector<uint32_t> &corridor,
                         const std::vector<std::vector<flight>> &adjacency_list,
                         const std::vector<airport> &nodes, OptimizeFor mode,
                         uint32_t start_time, RoutingResult &best_result,
                         RoutingMetrics &metrics) {

    std::vector<TimetableState> current_states;
    current_states.push_back({start_time, 0, {}});

    for (size_t hop = 0; hop + 1 < corridor.size(); ++hop) {
      uint32_t u = corridor[hop];
      uint32_t v = corridor[hop + 1];

      std::vector<TimetableState> next_states;

      for (const auto &state : current_states) {
        uint32_t req_dep = state.current_time + nodes[u].min_transfer;
        if (hop == 0) {
          req_dep = state.current_time;
        }

        for (const flight &f : adjacency_list[u]) {
          if (f.destination_id != v)
            continue;
          metrics.edges_relaxed++;

          int32_t origin_utc_offset = nodes[u].utc_offset_15m * 15;
          uint32_t abs_dep = static_cast<uint32_t>(
              static_cast<int32_t>(f.flight_day * 1440 + f.departure_time) -
              origin_utc_offset);

          if (abs_dep < req_dep)
            continue;

          uint32_t wait_time = abs_dep - state.current_time;
          if (wait_time > 1440)
            continue;

          uint32_t dur = f.duration_mins;
          uint32_t next_time = abs_dep + dur;
          uint32_t next_price = state.total_price + f.price;

          bool is_final_hop = (hop + 1 == corridor.size() - 1);
          bool dominated = false;
          for (const auto &existing : next_states) {
            if (existing.total_price <= next_price &&
                existing.current_time <= next_time) {
              if (is_final_hop || (next_time - existing.current_time <= 1440)) {
                dominated = true;
                break;
              }
            }
          }
          if (dominated)
            continue;

          next_states.erase(
              std::remove_if(next_states.begin(), next_states.end(),
                             [is_final_hop, next_price,
                              next_time](const TimetableState &s) {
                               return s.total_price >= next_price &&
                                      s.current_time >= next_time &&
                                      (is_final_hop ||
                                       (s.current_time - next_time <= 1440));
                             }),
              next_states.end());

          std::vector<flight> new_path = state.flights_taken;
          new_path.push_back(f);
          next_states.push_back({next_time, next_price, std::move(new_path)});
        }
      }

      current_states = std::move(next_states);
      if (current_states.empty()) {
        return;
      }
    }

    for (const auto &final_state : current_states) {
      uint32_t journey_time = final_state.current_time - start_time;

      bool is_better = false;
      if (!best_result.success) {
        is_better = true;
      } else if (mode == OptimizeFor::PRICE) {
        if (final_state.total_price < best_result.total_price ||
            (final_state.total_price == best_result.total_price &&
             journey_time < best_result.total_time_mins)) {
          is_better = true;
        }
      } else {
        if (journey_time < best_result.total_time_mins ||
            (journey_time == best_result.total_time_mins &&
             final_state.total_price < best_result.total_price)) {
          is_better = true;
        }
      }

      if (is_better) {
        best_result.success = true;
        best_result.total_price = final_state.total_price;
        best_result.total_time_mins = journey_time;
        best_result.path = final_state.flights_taken;
      } else if (best_result.success && final_state.total_price == best_result.total_price) {
        if (final_state.flights_taken.size() < best_result.path.size() ||
            (final_state.flights_taken.size() == best_result.path.size() &&
             journey_time < best_result.total_time_mins)) {
          best_result.total_time_mins = journey_time;
          best_result.path = final_state.flights_taken;
        }
      }
    }
  }
};
